% ============================================================
% GNN <-> COMSOL PIPELINE CONFIGURATION
%
% Single source of truth for every file path used by the
% GNN-COMSOL MATLAB scripts (prepare_gnn_comsol_pipeline,
% complete_pipeline_single_step, complete_pipeline_all_timesteps).
%
% Update the paths here when the COMSOL model, the GNN virtual
% environment, or the trained run directory change - every
% script picks up the change automatically.
% ============================================================

% COMSOL model.
% Study 1 / sol1 must already have been computed and saved
% by first_database.m.
cfg.model_file = ...
    '\\nl-filer1\users$\giovanni\Desktop\Comsol simulations\Reynolds dataset\channel2d_manual_stabilization_180R.mph';

% Dataset generated by first_database.m
cfg.dataset_file = ...
    'C:\Users\giovanni\.comsol\v64\llmatlab\channel2d_manual_stabilization_180R.mat';

% Python executable inside the GNN virtual environment
cfg.python_exe = ...
    'C:\Users\giovanni\gnn\.venv\Scripts\python.exe';

% Python inference script
cfg.python_script = ...
    'C:\Users\giovanni\gnn\scripts\evaluate_test.py';

% Trained GNN run
cfg.run_dir = ...
    'C:\Users\giovanni\gnn\outputs\BEST_CONFIGURATION';

% File produced by evaluate_test.py
cfg.gnn_predictions_file = ...
    'C:\Users\giovanni\.comsol\v64\llmatlab\gnn_predictions.mat';

% Files used by the COMSOL GNN interpolation functions
% (int4 = u, int5 = v, int6 = p)
cfg.u_gnn_file = ...
    'C:\Users\giovanni\.comsol\v64\llmatlab\u_gnn.txt';

cfg.v_gnn_file = ...
    'C:\Users\giovanni\.comsol\v64\llmatlab\v_gnn.txt';

cfg.p_gnn_file = ...
    'C:\Users\giovanni\.comsol\v64\llmatlab\p_gnn.txt';


%% ============================================================
% WHICH INITIAL GUESS THE SECOND SOLVE USES
% ============================================================
%
% Every transition is solved twice: once from the standard guess
% X^(0) = X_k, and once from the guess selected here. The first
% run is always the reference, so the two numbers printed side by
% side are always comparable.
%
% The point of the middle two options is that u,v and p come from
% two SEPARATE networks, trained independently. Nothing makes the
% pair (u,p) consistent, and in an incompressible solve the
% pressure is the multiplier that enforces div(u) = 0 for THAT
% velocity field: if it does not, Newton starts in the wrong
% direction. Swapping one of the two back to the exact COMSOL
% solution says which of the networks is responsible.
%
%   'gnn'                u,v and p from the network
%
%   'gnn_velocity_only'  u,v from the network, p from X_k.
%                        Isolates the cost of the predicted
%                        pressure: if the iteration count comes
%                        back to normal, the pressure is at fault.
%
%   'gnn_pressure_only'  p from the network, u,v from X_k.
%                        The mirror image.
%
%   'standard'           everything from X_k. A sanity check:
%                        the second solve must then take exactly
%                        as many iterations as the first, and any
%                        difference is an artefact of the harness
%                        rather than a property of the GNN.
%
% Note that X_k is read from the FEM degrees of freedom, while the
% network's fields go through an interpolation file. That
% asymmetry is unavoidable here, and it is one more reason to
% read 'standard' before trusting a small difference.
% ============================================================

cfg.initial_guess = 'gnn';

end
